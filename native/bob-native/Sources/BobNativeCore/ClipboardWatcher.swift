import AppKit

/// Reports copied text for the optional clipboard context (proposal 16). Off by default; when on, it checks
/// the pasteboard's change counter once a second (reading the counter does not read the contents) and only
/// reads plain text after a real change. Items marked concealed or transient (password managers, per the
/// nspasteboard.org convention), copies made by BOB itself and copies in quiet apps are never reported.
public final class ClipboardWatcher {
    /// Pasteboard types that mean "do not record this".
    public static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]
    public static let maxChars = 2000
    nonisolated(unsafe) private static var ignoreUntil = Date.distantPast

    /// BOB is about to borrow the clipboard (Selection Actions copy/paste fallback, Copy in the preview).
    public static func ignoreChanges(for seconds: TimeInterval) {
        ignoreUntil = Date().addingTimeInterval(seconds)
    }

    /// Decide whether a pasteboard item may be reported (pure, unit-tested).
    public static func reportable(types: [String], text: String?, frontmost: String?, exclude: Set<String>,
                                  now: Date = Date()) -> String? {
        guard now >= ignoreUntil, !types.contains(where: privateTypes.contains),
              let text, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
        if let frontmost, exclude.contains(frontmost) { return nil }
        return String(text.prefix(maxChars))
    }

    public var onText: ((String) -> Void)?
    public var exclude: Set<String> = []
    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount

    public init() {}

    public func setEnabled(_ on: Bool) {
        if on, timer == nil {
            lastCount = NSPasteboard.general.changeCount  // only copies made from now on
            timer = Timer.scheduledTimer(withTimeInterval: 1.0, repeats: true) { [weak self] _ in self?.tick() }
        } else if !on {
            timer?.invalidate()
            timer = nil
        }
    }

    private func tick() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        let types = (pb.types ?? []).map(\.rawValue)
        let front = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        let text = types.contains(where: Self.privateTypes.contains) ? nil : pb.string(forType: .string)
        if let t = Self.reportable(types: types, text: text, frontmost: front, exclude: exclude) { onText?(t) }
    }
}
